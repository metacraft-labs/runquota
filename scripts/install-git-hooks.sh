#!/usr/bin/env bash
# Installs this repository's committed .pre-commit-config.yaml as its
# pre-commit hook, run by the given pre-commit executable.
#
# The flake provides the tool, the committed config provides the rules
# (metacraft-dev-guidelines repo-requirements.md §4.1). git-hooks.nix's own
# installer cannot do this: it refuses to replace a committed
# .pre-commit-config.yaml and then installs nothing at all.
#
# The hook is written into the COMMON hooks directory, which every linked
# worktree shares. It names the config by a path relative to the worktree it
# runs in, so each worktree is judged by the config it has checked out, and
# every worktree has one because it is tracked.
#
# Reprobuild owns the hook dispatchers; this script owns only the local check.
# Where a dispatcher holds the `pre-commit` slot, the check is written as
# `pre-commit.repro-local`, which the dispatcher runs. A hook that neither a
# dispatcher, pre-commit, prek nor this script wrote is somebody's own, and is
# never replaced.
#
# Exits 0 without installing anything when the config is not the committed
# one (the message says how to restore it); exits 1 when a slot holds a hook
# it must not replace, or when core.hooksPath sends git to another directory.
#
#   bash scripts/install-git-hooks.sh /path/to/pre-commit
#   tests/test_linked_worktree_commits_without_its_dev_shell.sh
set -euo pipefail
pre_commit=$1
config=.pre-commit-config.yaml
marker='# git-hooks: generated by scripts/install-git-hooks.sh'
git rev-parse --git-dir >/dev/null 2>&1 || exit 0
repo_root=$(git rev-parse --show-toplevel)
config_path="$repo_root/$config"

# A /nix/store symlink here is the config git-hooks.nix generated before the
# file was committed; the committed file replaces it.
if [[ -L $config_path && $(readlink "$config_path") == /nix/store/* ]] &&
	git -C "$repo_root" cat-file -e "HEAD:$config" 2>/dev/null; then
	rm -f "$config_path"
	git -C "$repo_root" checkout HEAD -- "$config"
fi
if [[ ! -f $config_path || -L $config_path ]]; then
	echo "git-hooks: $config_path is not the committed config; restore it with" \
		"'git checkout HEAD -- $config'. No hooks were installed." >&2
	exit 0
fi

# Resolve the directory, not the hook: git dereferences hook symlinks.
hooks_dir=$(git rev-parse --path-format=absolute --git-common-dir)/hooks
# A core.hooksPath that points elsewhere (a global one, or another tool's)
# means git never runs what is written here: refuse rather than report an
# installed gate that does not run. `--git-path hooks` is the directory git
# actually runs hooks from.
effective_hooks=$(git rev-parse --path-format=absolute --git-path hooks 2>/dev/null || true)
if [[ -z $effective_hooks || $(realpath -m -- "$effective_hooks") != $(realpath -m -- "$hooks_dir") ]]; then
	echo "git-hooks: git runs hooks from '${effective_hooks:-an unresolvable core.hooksPath}'," \
		"not $hooks_dir, so a hook installed there would never run; unset or" \
		"correct core.hooksPath. No hooks were installed." >&2
	exit 1
fi
hook="$hooks_dir/pre-commit"
if [[ -f $hook && ! -L $hook ]] && grep -q 'reprobuild hook dispatcher' "$hook"; then
	hook="$hook.repro-local"
fi
if [[ -L $hook ]]; then
	echo "git-hooks: refusing to replace the symlink hook $hook." >&2
	exit 1
fi
if [[ -e $hook ]] && { [[ ! -f $hook ]] || ! grep -Eq "^(# File generated by (pre-commit|prek)|$marker)" "$hook"; }; then
	echo "git-hooks: refusing to replace $hook, which is not a pre-commit hook;" \
		"run 'repro hooks ensure --vcs' to reconcile." >&2
	exit 1
fi

mkdir -p "$hooks_dir"
tmp="$(mktemp "$hook.XXXXXX")"
# The single-quoted lines are the hook's own shell code, expanded when it runs.
# shellcheck disable=SC2016
{
	printf '%s\n' '#!/usr/bin/env bash' "$marker"
	# The executable the dev shell provided, while it exists. A Nix garbage
	# collection can remove it; then the pre-commit on PATH, and failing that
	# a refusal that says what to do, never a silently skipped check.
	printf 'pre_commit=%q\n' "$pre_commit"
	printf '%s\n' \
		'if [ ! -x "$pre_commit" ]; then' \
		'  pre_commit="$(command -v pre-commit || true)"' \
		'fi' \
		'if [ -z "$pre_commit" ]; then' \
		'  echo "pre-commit hook: pre-commit is not installed; enter the dev shell (nix develop) once to reinstall this hook." >&2' \
		'  exit 1' \
		'fi'
	# hook-impl keeps pre-commit's handling of stdin, arguments and the
	# framework's `.legacy` chain; `run` does not.
	printf 'exec "$pre_commit" hook-impl --config %q --hook-type pre-commit --hook-dir %q -- "$@"\n' \
		"$config" "$hooks_dir"
} >"$tmp"
chmod 755 "$tmp"
mv -f "$tmp" "$hook"
